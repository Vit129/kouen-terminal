#!/usr/bin/env python3
"""Generate pinned Unicode18 grapheme tables and the official conformance corpus.

Run from any directory; output paths are relative to this script's repository.
Optional --ucd-dir reads the four source files by basename instead of downloading.
"""
import argparse
import hashlib
from pathlib import Path
from urllib.request import urlopen

VERSION = "18.0.0"
SOURCES = {
    "auxiliary/GraphemeBreakProperty.txt": "0839dcb79e4ac639ecd538b1abf7c9d22e3f9dd265b7e182d33627aa4d75b45a",
    "DerivedCoreProperties.txt": "09c928886a178fcafd93c29e4bd59073a058e5a100b716d425cb563ab50f68c9",
    "emoji/emoji-data.txt": "80d00f8e616a0ef27fd6b8de3b758c06383b5d917e2977709578e68baf733bf1",
    "auxiliary/GraphemeBreakTest.txt": "b0cf047ee94485bbdc846de2b902f5f8a815f6b674f9d04223cddadd91c9df31",
}
PROPERTIES = ["Other", "CR", "LF", "Control", "Extend", "ZWJ", "Regional_Indicator",
              "Prepend", "SpacingMark", "L", "V", "T", "LV", "LVT"]
HEADER = """// GENERATED by Scripts/generate-grapheme-table.py — DO NOT EDIT BY HAND.
// Unicode18.0.0; source URLs and SHA-256 hashes are pinned in the generator.
// Data derived from the Unicode Character Database, © Unicode, Inc.
// License: https://www.unicode.org/license.txt
"""


def read(name, directory):
    if directory:
        data = (directory / Path(name).name).read_bytes()
    else:
        with urlopen(f"https://www.unicode.org/Public/{VERSION}/ucd/{name}", timeout=30) as response:
            data = response.read()
    if hashlib.sha256(data).hexdigest() != SOURCES[name]:
        raise ValueError(f"{name}: checksum does not match Unicode {VERSION}")
    return data.decode("utf-8")


def records(text):
    for line in text.splitlines():
        fields = [field.strip() for field in line.split("#", 1)[0].split(";")]
        if len(fields) < 2:
            continue
        bounds = fields[0].split("..")
        yield range(int(bounds[0], 16), int(bounds[-1], 16) + 1), fields[1:]


def array(name, kind, values):
    lines = [f"    static let {name}: [{kind}] = ["]
    for index in range(0, len(values), 24):
        lines.append("        " + ", ".join(map(str, values[index:index + 24])) + ",")
    return "\n".join(lines + ["    ]"])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--ucd-dir", type=Path)
    args = parser.parse_args()
    sources = {name: read(name, args.ucd_dir) for name in SOURCES}
    properties = bytearray(0x110000)
    for scalars, fields in records(sources["auxiliary/GraphemeBreakProperty.txt"]):
        for scalar in scalars:
            properties[scalar] = PROPERTIES.index(fields[0])
    for scalars, fields in records(sources["DerivedCoreProperties.txt"]):
        if fields[0] == "InCB":
            code = ["None", "Consonant", "Extend", "Linker"].index(fields[1]) << 4
            for scalar in scalars:
                properties[scalar] |= code
    for scalars, fields in records(sources["emoji/emoji-data.txt"]):
        if fields[0] not in {"Extended_Pictographic", "Emoji"}:
            continue
        bit = 64 if fields[0] == "Extended_Pictographic" else 128
        for scalar in scalars:
            properties[scalar] |= bit
    indices, blocks, block_ids = [], [], {}
    for offset in range(0, len(properties), 256):
        block = bytes(properties[offset:offset + 256])
        if block not in block_ids:
            block_ids[block] = len(blocks)
            blocks.append(block)
        indices.append(block_ids[block])
    root = Path(__file__).resolve().parent.parent
    output = root / "Packages/HarnessTerminalEngine/Sources/HarnessTerminalEngine/Width/GraphemeBreakTable.swift"
    output.write_text(HEADER + "\nenum GraphemeBreakTable {\n"
                      + f'    static let unicodeVersion = "{VERSION}"\n'
                      + array("indices", "UInt16", indices) + "\n"
                      + array("properties", "UInt8", b"".join(blocks)) + "\n}\n")
    cases = [line.split("#", 1)[0].strip() for line in sources["auxiliary/GraphemeBreakTest.txt"].splitlines()]
    corpus = "\n".join(line for line in cases if line)
    output = root / "Tests/HarnessTerminalEngineTests/Unicode18GraphemeCorpus.swift"
    output.write_text(HEADER + '\nenum Unicode18GraphemeCorpus {\n    static let cases = """\n'
                      + corpus + '\n"""\n}\n')


if __name__ == "__main__":
    main()
